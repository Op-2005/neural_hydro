"""Recompute every load-bearing number for the XAI4Science submission from raw runs.

This is the step-1 gate of paper/workshops/xai4science/PLAN.md: no sentence of the
submission is written until its number appears in this script's output. Nothing here
reads a paper, a summary, or another workshop version -- only
runs/topology_ablation/component0/<cond>_component0_seed<s>/test/model_epoch030/test_metrics.csv
and the connected-basin / edge artifacts that define the strata.

Two estimators are reported wherever both are in use, because they differ in the third
decimal and every caption must declare which it quotes:
  pooled     -- median over all basin x seed pairs
  cross-seed -- mean of the per-seed medians

Significance follows the project rule: judged by the WEAKEST of the three seeds, never pooled.

Usage: python experiments/topology_ablation/recompute_xai4science.py
Writes: experiments/topology_ablation/analysis/XAI4SCIENCE_NUMBERS.md
"""
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

ROOT = Path(__file__).parent.parent.parent
BASE = ROOT / "runs" / "topology_ablation" / "component0"
EDGES = ROOT / "topology_analysis/phase1_network_discovery/outputs/component0_edges.csv"
OUT = Path(__file__).parent / "analysis" / "XAI4SCIENCE_NUMBERS.md"
SEEDS = [11, 13, 17]


def nse(cond, seed):
    p = BASE / f"{cond}_component0_seed{seed}" / "test" / "model_epoch030" / "test_metrics.csv"
    if not p.exists():
        return None
    return pd.read_csv(p, dtype={"basin": str}).set_index("basin")["NSE"]


def connected_basins():
    """Basins with >=1 upstream neighbour under the true network."""
    e = pd.read_csv(EDGES, dtype={"parent_id": str, "child_id": str})
    return set(e["child_id"].unique())


def paired(cond, ref="L", basins=None, alternative="greater"):
    """Per-seed paired deltas vs ref. Returns (per_seed_medians, per_seed_p, pooled_median)."""
    meds, ps, pooled = [], [], []
    for s in SEEDS:
        a, b = nse(cond, s), nse(ref, s)
        if a is None or b is None:
            return None, None, None
        idx = a.index.intersection(b.index)
        if basins is not None:
            idx = idx.intersection(basins)
        d = (a.loc[idx] - b.loc[idx]).dropna()
        meds.append(float(d.median()))
        ps.append(float(wilcoxon(d, alternative=alternative).pvalue))
        pooled.append(d)
    return meds, ps, float(pd.concat(pooled).median())


def fmt(xs, p=4):
    return " / ".join(f"{x:+.{p}f}" for x in xs)


def row(label, cond, ref="L", basins=None, alternative="greater"):
    meds, ps, pool = paired(cond, ref, basins, alternative)
    if meds is None:
        return f"| {label} | run missing | -- | -- | -- |", None
    cs = float(np.mean(meds))
    return (f"| {label} | {fmt(meds)} | {cs:+.4f} | {pool:+.4f} | {max(ps):.2g} |",
            dict(per_seed=meds, cross=cs, pooled=pool, weakest_p=max(ps)))


def main():
    conn = connected_basins()
    md = ["# XAI4Science — load-bearing numbers, recomputed from raw runs", "",
          "Generated by `recompute_xai4science.py`. Every number the submission prints must",
          "appear here first. Significance = weakest of seeds 11/13/17 (never pooled).", "",
          f"Connected basins (>=1 upstream neighbour under the true network): **{len(conn)}**", ""]

    # ---- condition medians ------------------------------------------------
    md += ["## Median NSE by condition (all 183 basins)", "",
           "| Condition | per-seed median | mean +/- std |", "|---|---|---|"]
    for cond in ["L", "L_T", "L_noID", "L_noID_T", "L_upQ", "L_upQpred", "L_upQshuf",
                 "L_upPrecip", "L_upQknn2", "L_upQpredknn2", "L_upQknn2min15km",
                 "L_upQdistctrl"]:
        v = [nse(cond, s) for s in SEEDS]
        if any(x is None for x in v):
            md.append(f"| {cond} | run missing | -- |")
            continue
        m = [float(x.median()) for x in v]
        md.append(f"| `{cond}` | {' / '.join(f'{x:.4f}' for x in m)} | "
                  f"{np.mean(m):.4f} +/- {np.std(m, ddof=1):.4f} |")

    # ---- H1: form decides -------------------------------------------------
    md += ["", "## H1 — form decides (all 183 basins, paired vs L)", "",
           "| Contrast | per-seed median | cross-seed | pooled | weakest-seed p |", "|---|---|---|---|---|"]
    h1 = {}
    for lab, c, r, alt in [("static topology, with one-hot (L_T - L)", "L_T", "L", "two-sided"),
                           ("static topology, no one-hot (L_noID_T - L_noID)", "L_noID_T", "L_noID", "two-sided"),
                           ("basin one-hot (L - L_noID)", "L", "L_noID", "greater"),
                           ("oracle (L_upQ - L)", "L_upQ", "L", "greater"),
                           ("realizable (L_upQpred - L)", "L_upQpred", "L", "greater"),
                           ("shuffled null (L_upQshuf - L)", "L_upQshuf", "L", "two-sided")]:
        line, d = row(lab, c, r, None, alt)
        md.append(line)
        h1[c + "-" + r] = d

    # ---- H2: selector comparison, connected basins ------------------------
    md += ["", "## H2 — neighbour selection (connected basins only, paired vs L)", "",
           "| Contrast | per-seed median | cross-seed | pooled | weakest-seed p |", "|---|---|---|---|---|"]
    for lab, c in [("network oracle (L_upQ - L)", "L_upQ"),
                   ("nearest-2 oracle (L_upQknn2 - L)", "L_upQknn2"),
                   ("nearest-2, >=15 km floor (L_upQknn2min15km - L)", "L_upQknn2min15km"),
                   ("network realizable (L_upQpred - L)", "L_upQpred"),
                   ("nearest-2 realizable (L_upQpredknn2 - L)", "L_upQpredknn2"),
                   ("distance-matched control (L_upQdistctrl - L)", "L_upQdistctrl"),
                   ("upstream precipitation (L_upPrecip - L)", "L_upPrecip")]:
        line, _ = row(lab, c, "L", conn, "greater")
        md.append(line)

    # ---- head-to-head: the headline ---------------------------------------
    md += ["", "## Head-to-head (connected basins) — the headline contrast", "",
           "| Contrast | per-seed median | cross-seed | pooled | weakest-seed p |", "|---|---|---|---|---|"]
    for lab, c, r in [("nearest-2 - network, ORACLE", "L_upQknn2", "L_upQ"),
                      ("nearest-2 - network, >=15 km floor", "L_upQknn2min15km", "L_upQ"),
                      ("nearest-2 - network, REALIZABLE (deployable)", "L_upQpredknn2", "L_upQpred"),
                      ("distance-matched - network (TOST target)", "L_upQdistctrl", "L_upQ"),
                      ("discharge over precipitation", "L_upQpred", "L_upPrecip")]:
        line, _ = row(lab, c, r, conn, "two-sided")
        md.append(line)

    # ---- distance sweep (single seed, read for shape) ----------------------
    md += ["", "## Distance sweep (seed 11 only — read for SHAPE, not per-point values)", "",
           "| Substitute-edge distance | median dNSE vs L (connected) |", "|---|---|"]
    sweep = []
    for tag, km in [("L_upQdistctrl", 101), ("L_upQdist175km", 175), ("L_upQdist250km", 250),
                    ("L_upQdist350km", 350), ("L_upQdist500km", 500)]:
        a, b = nse(tag, 11), nse("L", 11)
        if a is None:
            md.append(f"| {km} km | run missing |")
            continue
        idx = a.index.intersection(b.index).intersection(conn)
        d = float((a.loc[idx] - b.loc[idx]).dropna().median())
        sweep.append((km, d))
        md.append(f"| {km} km | {d:+.4f} |")
    if len(sweep) > 2:
        from scipy.stats import spearmanr
        rs = spearmanr([x[0] for x in sweep], [x[1] for x in sweep])
        md.append(f"\nSpearman r_s (distance vs gain) = **{rs.statistic:+.3f}** (p={rs.pvalue:.3g})")

    md += ["", "---", "",
           "Estimators: *pooled* = median over all basin x seed pairs; *cross-seed* = mean of",
           "per-seed medians. They differ in the third decimal by construction; every caption",
           "in the submission must declare which one it quotes.", ""]

    OUT.write_text("\n".join(md) + "\n")
    print("\n".join(md))
    print(f"\nwrote {OUT}")


if __name__ == "__main__":
    main()
